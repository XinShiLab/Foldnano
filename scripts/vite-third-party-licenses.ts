import { existsSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';

export const THIRD_PARTY_LICENSES_FILE = 'third-party-licenses.txt';

interface PackageInfo {
	name: string;
	version: string;
	license: string;
	author: string;
	licenseText: string | null;
}

const LICENSE_FILE_PATTERN = /^(licen[cs]e|copying|notice)(\.|-|$)/i;

function packageDirFromModuleId(id: string): string | null {
	const cleanId = id.replace(/^\0/, '').split('?')[0];
	const marker = `${path.sep}node_modules${path.sep}`;
	const idx = cleanId.lastIndexOf(marker);
	if (idx === -1) return null;
	const rest = cleanId.slice(idx + marker.length).split(path.sep);
	const nameParts = rest[0].startsWith('@') ? rest.slice(0, 2) : rest.slice(0, 1);
	return cleanId.slice(0, idx + marker.length) + nameParts.join(path.sep);
}

function formatAuthor(author: unknown): string {
	if (typeof author === 'string') return author;
	if (author && typeof author === 'object' && 'name' in author) return String(author.name);
	return '';
}

// Some packages omit `license` in package.json but ship a LICENSE file headed e.g. "MIT License".
function licenseFromText(text: string | null): string {
	const firstLine = text?.split('\n')[0].trim() ?? '';
	return /licen[cs]e$/i.test(firstLine) ? `${firstLine} (from LICENSE file)` : 'UNKNOWN';
}

function readPackageInfo(dir: string): PackageInfo | null {
	const pkgPath = path.join(dir, 'package.json');
	if (!existsSync(pkgPath)) return null;
	const pkg = JSON.parse(readFileSync(pkgPath, 'utf8')) as Record<string, unknown>;
	const licenseFiles = readdirSync(dir)
		.filter((f) => LICENSE_FILE_PATTERN.test(f))
		.sort();
	const licenseText = licenseFiles.length
		? licenseFiles.map((f) => readFileSync(path.join(dir, f), 'utf8').trim()).join('\n\n')
		: null;
	return {
		name: String(pkg.name ?? path.basename(dir)),
		version: String(pkg.version ?? ''),
		license: typeof pkg.license === 'string' ? pkg.license : licenseFromText(licenseText),
		author: formatAuthor(pkg.author),
		licenseText,
	};
}

function renderLicenses(packages: PackageInfo[]): string {
	const header = [
		'Foldnano third-party licenses',
		'=============================',
		'',
		'Foldnano is released under the MIT License.',
		'This file is generated at build time and lists every third-party npm package',
		'bundled into this build of the web app, with its license text.',
		'',
		'Pyodide and its Python packages are loaded at runtime from the Pyodide CDN and',
		'are not bundled; see https://github.com/pyodide/pyodide (MPL-2.0).',
		'cadnano (BSD 3-Clause, Wyss Institute) is credited in THIRD_PARTY_NOTICES.md',
		'in the source repository.',
		'',
	].join('\n');
	const sections = packages.map((p) => {
		const lines = ['-'.repeat(80), `${p.name}@${p.version}`, `License: ${p.license}`];
		if (p.author) lines.push(`Author: ${p.author}`);
		lines.push('', p.licenseText ?? '(No license file shipped with this package.)', '');
		return lines.join('\n');
	});
	return `${header}\n${sections.join('\n')}`;
}

// Workers are bundled in nested builds that finish before the client's generateBundle,
// so one shared collector sees both and the client build writes the combined file.
export function thirdPartyLicenses(): {
	client: Plugin;
	worker: () => Plugin;
	devNotice: Plugin;
} {
	const packageDirs = new Set<string>();

	const collect = (bundle: Record<string, { type: string; modules?: object }>): void => {
		for (const output of Object.values(bundle)) {
			if (output.type !== 'chunk' || !output.modules) continue;
			for (const id of Object.keys(output.modules)) {
				const dir = packageDirFromModuleId(id);
				if (dir) packageDirs.add(dir);
			}
		}
	};

	const client: Plugin = {
		name: 'foldnano:third-party-licenses',
		apply: 'build',
		applyToEnvironment: (env) => env.config.consumer === 'client',
		generateBundle(_options, bundle) {
			collect(bundle);
			const byName = new Map<string, PackageInfo>();
			for (const dir of packageDirs) {
				const info = readPackageInfo(dir);
				if (info && info.name !== 'foldnano') byName.set(`${info.name}@${info.version}`, info);
			}
			const packages = [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
			this.emitFile({
				type: 'asset',
				fileName: THIRD_PARTY_LICENSES_FILE,
				source: renderLicenses(packages),
			});
		},
	};

	const worker = (): Plugin => ({
		name: 'foldnano:third-party-licenses-worker',
		apply: 'build',
		generateBundle(_options, bundle) {
			collect(bundle);
		},
	});

	const devNotice: Plugin = {
		name: 'foldnano:third-party-licenses-dev',
		apply: 'serve',
		configureServer(server) {
			server.middlewares.use(`/${THIRD_PARTY_LICENSES_FILE}`, (_req, res) => {
				res.setHeader('Content-Type', 'text/plain; charset=utf-8');
				res.end('This file is generated by `pnpm build` from the bundled npm packages.\n');
			});
		},
	};

	return { client, worker, devNotice };
}
