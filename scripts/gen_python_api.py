#!/usr/bin/env python3
"""Generate the plugin Python API stubs (.pyi) and the Script Lab autocomplete index.

Reads the bundled `foldnano` and `foldnano_mini` packages with `ast` (nothing is imported)
and writes, from the same pass:

  src/lib/plugin/python/stubs/<package>/__init__.pyi   every public definition, full docstrings
  src/lib/plugin/python/stubs/<package>/<module>.pyi   re-export shims for submodule imports
  src/lib/plugin/python-api-index.generated.json         member/type index for editor completions

Usage:
  python3 scripts/gen_python_api.py          # regenerate
  python3 scripts/gen_python_api.py --check  # exit 1 if any output is stale
"""

from __future__ import annotations

import ast
import copy
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY_ROOT = ROOT / "src/lib/plugin/python"
STUB_ROOT = PY_ROOT / "stubs"
INDEX_PATH = ROOT / "src/lib/plugin/python-api-index.generated.json"
PACKAGES = ["foldnano", "foldnano_mini"]

HEADER = "# Generated by scripts/gen_python_api.py from src/lib/plugin/python. Do not edit.\n"


class ClassInfo:
    def __init__(self, node: ast.ClassDef, module: str, source: str) -> None:
        self.node = node
        self.module = module
        self.source = source
        self.name = node.name
        self.bases = [ast.unparse(b) for b in node.bases]


def parse_module(path: Path) -> ast.Module:
    return ast.parse(path.read_text(encoding="utf-8"), filename=str(path))


def package_exports(pkg: str) -> tuple[list[str], dict[str, str]]:
    """Return (__all__, name -> submodule) for a package's __init__.py."""
    tree = parse_module(PY_ROOT / pkg / "__init__.py")
    origin: dict[str, str] = {}
    exports: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.level == 1 and node.module:
            for alias in node.names:
                origin[alias.asname or alias.name] = node.module
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets
        ):
            exports = [ast.literal_eval(e) for e in node.value.elts]  # type: ignore[attr-defined]
    missing = [name for name in exports if name not in origin]
    if missing:
        raise SystemExit(f"{pkg}/__init__.py: __all__ names not imported from a submodule: {missing}")
    return exports, origin


def first_paragraph(doc: str | None) -> str:
    if not doc:
        return ""
    para = doc.strip().split("\n\n", 1)[0]
    return " ".join(line.strip() for line in para.splitlines())


def norm_type(text: str | None) -> str | None:
    if text is None:
        return None
    return text.replace("'", "").replace('"', "")


def is_dataclass(node: ast.ClassDef) -> bool:
    return any(ast.unparse(d).split("(")[0] in ("dataclass", "dataclasses.dataclass") for d in node.decorator_list)


def decorator_names(fn: ast.FunctionDef) -> list[str]:
    return [ast.unparse(d) for d in fn.decorator_list]


def signature_text(fn: ast.FunctionDef, drop_first: bool) -> str:
    args = copy.copy(fn.args)
    if drop_first:
        if args.posonlyargs:
            args.posonlyargs = args.posonlyargs[1:]
        elif args.args:
            args.args = args.args[1:]
    return f"({ast.unparse(args)})"


def init_attributes(cls: ast.ClassDef) -> list[tuple[str, str]]:
    """Public `self.x` attributes assigned in __init__, typed from annotations or matching params."""
    init = next((n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == "__init__"), None)
    if init is None:
        return []
    params = {a.arg: ast.unparse(a.annotation) for a in init.args.args + init.args.kwonlyargs if a.annotation}
    seen: dict[str, str] = {}
    for node in ast.walk(init):
        target = value = annotation = None
        if isinstance(node, ast.AnnAssign):
            target, annotation, value = node.target, ast.unparse(node.annotation), node.value
        elif isinstance(node, ast.Assign) and len(node.targets) == 1:
            target, value = node.targets[0], node.value
        if not (
            isinstance(target, ast.Attribute)
            and isinstance(target.value, ast.Name)
            and target.value.id == "self"
            and not target.attr.startswith("_")
        ):
            continue
        if annotation is None and isinstance(value, ast.Name):
            annotation = params.get(value.id)
        if target.attr not in seen or (annotation and seen[target.attr] == "Any"):
            seen[target.attr] = annotation or "Any"
    return list(seen.items())


def class_members(info: ClassInfo) -> list[dict]:
    """Public members of one class body, in source order, for the completion index."""
    members: dict[str, dict] = {}
    node = info.node
    if is_dataclass(node):
        for stmt in node.body:
            if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                name = stmt.target.id
                if not name.startswith("_"):
                    members[name] = {"name": name, "kind": "attribute", "type": norm_type(ast.unparse(stmt.annotation))}
    for name, annotation in init_attributes(node):
        members.setdefault(name, {"name": name, "kind": "attribute", "type": norm_type(annotation)})
    for stmt in node.body:
        if not isinstance(stmt, ast.FunctionDef) or stmt.name.startswith("_"):
            continue
        decs = decorator_names(stmt)
        if any(d.endswith(".setter") for d in decs):
            if stmt.name in members:
                members[stmt.name]["settable"] = True
            else:
                # `@Base.prop.setter` in a subclass: settable here, typed by the base (see flattened).
                members[stmt.name] = {"name": stmt.name, "kind": "property", "settable": True, "inherit": True}
            continue
        doc = first_paragraph(ast.get_docstring(stmt))
        returns = norm_type(ast.unparse(stmt.returns)) if stmt.returns else None
        if "property" in decs:
            entry = {"name": stmt.name, "kind": "property", "type": returns}
        else:
            entry = {
                "name": stmt.name,
                "kind": "method",
                "signature": signature_text(stmt, drop_first="staticmethod" not in decs),
                "returns": returns,
            }
        if doc:
            entry["doc"] = doc
        members[stmt.name] = entry
    return list(members.values())


def collect_package(pkg: str) -> dict:
    exports, origin = package_exports(pkg)
    modules: dict[str, ast.Module] = {}
    sources: dict[str, str] = {}
    for sub in sorted(set(origin.values())):
        path = PY_ROOT / pkg / f"{sub}.py"
        sources[sub] = path.read_text(encoding="utf-8")
        modules[sub] = parse_module(path)

    classes: dict[str, ClassInfo] = {}
    functions: dict[str, tuple[ast.FunctionDef, str]] = {}
    constants: dict[str, tuple[ast.stmt, str]] = {}
    for sub, tree in modules.items():
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                classes[node.name] = ClassInfo(node, sub, sources[sub])
            elif isinstance(node, ast.FunctionDef):
                functions[node.name] = (node, sub)
            elif isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                for t in targets:
                    if isinstance(t, ast.Name):
                        constants[t.id] = (node, sub)

    for name in exports:
        if name not in classes and name not in functions and name not in constants:
            raise SystemExit(f"{pkg}: exported name {name!r} not found in {origin[name]}.py")

    # Private helper classes (e.g. a `_Vec3` field type) referenced by exported definitions.
    exported_src = " ".join(ast.unparse(classes[n].node) for n in exports if n in classes)
    helpers = [n for n in classes if n.startswith("_") and n in exported_src]

    return {
        "pkg": pkg,
        "exports": exports,
        "origin": origin,
        "classes": classes,
        "functions": functions,
        "constants": constants,
        "helpers": helpers,
        "imports": [m for tree in modules.values() for m in stub_imports(tree)],
    }


def stub_imports(tree: ast.Module) -> list[str]:
    """`typing` names the source modules import; the stub keeps those its text actually uses."""
    return [
        alias.name
        for node in tree.body
        if isinstance(node, ast.ImportFrom) and node.module == "typing"
        for alias in node.names
        if alias.name != "TYPE_CHECKING"
    ]


# ---------------------------------------------------------------------------
# .pyi rendering
# ---------------------------------------------------------------------------


def indent(text: str, prefix: str) -> str:
    return "\n".join(prefix + line if line.strip() else "" for line in text.splitlines())


def docstring_block(doc: str | None, prefix: str) -> str:
    if not doc:
        return ""
    body = doc.replace('"""', '\\"\\"\\"')
    if "\n" in body:
        return f'{prefix}"""\n{indent(body, prefix)}\n{prefix}"""\n'
    return f'{prefix}"""{body}"""\n'


def render_function(fn: ast.FunctionDef, prefix: str) -> str:
    stub = copy.copy(fn)
    stub.body = [ast.Expr(ast.Constant(...))]
    lines = ast.unparse(stub).splitlines()
    doc = ast.get_docstring(fn)
    if not doc:
        return indent("\n".join(lines[:-2] + [lines[-2] + " ..."]), prefix) + "\n"
    head = "\n".join(lines[:-1])
    return indent(head, prefix) + "\n" + docstring_block(doc, prefix + "    ")


def render_class(info: ClassInfo) -> str:
    node = info.node
    bases = f"({', '.join(info.bases)})" if info.bases else ""
    decorators = "".join(f"@{ast.unparse(d)}\n" for d in node.decorator_list)
    out = [f"{decorators}class {node.name}{bases}:\n"]
    doc = ast.get_docstring(node)
    if doc:
        out.append(docstring_block(doc, "    "))
    body: list[str] = []
    if is_dataclass(node):
        for stmt in node.body:
            if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                body.append(f"    {stmt.target.id}: {ast.unparse(stmt.annotation)}\n")
    else:
        for name, annotation in init_attributes(node):
            body.append(f"    {name}: {annotation}\n")
    for stmt in node.body:
        if isinstance(stmt, ast.FunctionDef) and (not stmt.name.startswith("_") or stmt.name == "__init__"):
            if stmt.name == "__init__" and is_dataclass(node):
                continue
            body.append(render_function(stmt, "    "))
    if not body and not doc:
        body.append("    ...\n")
    out.append("\n".join(body))
    return "".join(out)


def render_package_stub(data: dict) -> str:
    pkg = data["pkg"]
    tree = parse_module(PY_ROOT / pkg / "__init__.py")
    parts = [HEADER, docstring_block(ast.get_docstring(tree), ""), "\n"]
    parts.append("from __future__ import annotations\n")
    body = "".join(render_class(c) for c in data["classes"].values()) + "".join(
        ast.unparse(fn) for fn, _ in data["functions"].values()
    )
    # Unexported type aliases (`RegionKind = Literal[...]`) that exported annotations use.
    aliases = [
        ast.unparse(node)
        for name, (node, _) in data["constants"].items()
        if name not in data["exports"]
        and isinstance(node, ast.Assign)
        and isinstance(node.value, ast.Subscript)
        and re.search(rf"\b{name}\b", body)
    ]
    used = body + "".join(aliases)
    typing_names = sorted({n for n in data["imports"] if re.search(rf"\b{n}\b", used)})
    if "@dataclass" in body:
        parts.append("\nfrom dataclasses import dataclass")
    if typing_names:
        parts.append(f"\nfrom typing import {', '.join(typing_names)}")
    parts.append("\n")
    parts.extend(f"\n{alias}\n" for alias in aliases)
    parts.append("\n__all__ = [\n" + "".join(f'    "{n}",\n' for n in data["exports"]) + "]\n")

    ordered: list[str] = list(data["helpers"])
    # Base classes before subclasses so the stub reads top-down.
    for name in data["exports"]:
        if name in data["classes"]:
            for base in data["classes"][name].bases:
                if base in data["classes"] and base not in ordered:
                    ordered.append(base)
            if name not in ordered:
                ordered.append(name)

    for name in data["exports"]:
        if name in data["constants"]:
            node, _ = data["constants"][name]
            annotation = ast.unparse(node.annotation) if isinstance(node, ast.AnnAssign) else None
            if annotation is None and isinstance(node.value, ast.Call):
                annotation = ast.unparse(node.value.func)
            parts.append(f"\n{name}: {annotation or 'Any'}\n")
    for name in data["exports"]:
        if name in data["functions"]:
            parts.append("\n\n" + render_function(data["functions"][name][0], ""))
    for name in ordered:
        parts.append("\n\n" + render_class(data["classes"][name]))
    return "".join(parts).rstrip() + "\n"


def render_submodule_shims(data: dict) -> dict[str, str]:
    by_module: dict[str, list[str]] = {}
    for name in data["exports"]:
        by_module.setdefault(data["origin"][name], []).append(name)
    shims = {}
    for module, names in sorted(by_module.items()):
        imports = ", ".join(f"{n} as {n}" for n in names)
        shims[module] = f"{HEADER}from {data['pkg']} import {imports}\n"
    return shims


# ---------------------------------------------------------------------------
# Completion index
# ---------------------------------------------------------------------------


def build_index(packages: list[dict]) -> dict:
    classes: dict[str, dict] = {}
    functions: dict[str, dict] = {}
    modules: dict[str, list[str]] = {}
    owner: dict[str, str] = {}

    for data in packages:
        pkg = data["pkg"]
        modules[pkg] = list(data["exports"])
        for name in data["exports"]:
            sub = f"{pkg}.{data['origin'][name]}"
            modules.setdefault(sub, []).append(name)
            if name in data["classes"]:
                if name in owner:
                    raise SystemExit(f"Class name {name!r} exported by both {owner[name]} and {pkg}")
                owner[name] = pkg
                info = data["classes"][name]
                classes[name] = {
                    "module": pkg,
                    "bases": [b for b in info.bases if b != "Protocol"],
                    "doc": first_paragraph(ast.get_docstring(info.node)),
                    "members": class_members(info),
                }
            elif name in data["functions"]:
                fn, _ = data["functions"][name]
                functions[name] = {
                    "module": pkg,
                    "signature": signature_text(fn, drop_first=False),
                    "returns": norm_type(ast.unparse(fn.returns)) if fn.returns else None,
                    "doc": first_paragraph(ast.get_docstring(fn)),
                }

    # Flatten inherited members so the editor never walks bases.
    def flattened(name: str, stack: tuple[str, ...] = ()) -> list[dict]:
        cls = classes[name]
        own = {m["name"] for m in cls["members"]}
        from_bases = []
        for base in cls["bases"]:
            if base in classes and base not in stack:
                from_bases += flattened(base, stack + (name,))
        members = []
        for m in cls["members"]:
            if m.pop("inherit", False):
                base_member = next((b for b in from_bases if b["name"] == m["name"]), {})
                m = {**base_member, **m}
            members.append(m)
        return members + [m for m in from_bases if m["name"] not in own]

    for name in classes:
        classes[name]["members"] = flattened(name)
    for cls in classes.values():
        del cls["bases"]

    return {"modules": modules, "functions": functions, "classes": classes}


def render_outputs() -> dict[Path, str]:
    packages = [collect_package(pkg) for pkg in PACKAGES]
    outputs: dict[Path, str] = {}
    for data in packages:
        outputs[STUB_ROOT / data["pkg"] / "__init__.pyi"] = render_package_stub(data)
        for module, text in render_submodule_shims(data).items():
            outputs[STUB_ROOT / data["pkg"] / f"{module}.pyi"] = text
    outputs[INDEX_PATH] = json.dumps(build_index(packages), indent="\t") + "\n"
    return outputs


def main() -> int:
    check = "--check" in sys.argv[1:]
    outputs = render_outputs()
    expected = set(outputs)
    existing = set(STUB_ROOT.rglob("*.pyi")) if STUB_ROOT.exists() else set()
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    orphans = sorted(existing - expected)

    if check:
        if stale or orphans:
            for p in stale + orphans:
                print(f"stale: {p.relative_to(ROOT)}")
            print("Run `pnpm gen:python-api` and commit the result.")
            return 1
        return 0

    for p in orphans:
        p.unlink()
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
