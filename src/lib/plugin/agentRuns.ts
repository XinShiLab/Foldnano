/** Marker that tells a generated run.py (safe to replace) from one the author wrote. */
const CLI_MARKER = 'Generated by Foldnano (agent runs';

/** `describe` runs no Python: the record only carries the design overview. */
export type AgentRequestKind = 'run' | 'describe';

/**
 * What happens to a run's change. `apply`: applied straight away. `ask-user`: a real change, held
 * for the user to Apply or Discard. `dry-run`: applied to a scratch copy for the overview, then
 * thrown away.
 */
export type AgentRunMode = 'apply' | 'ask-user' | 'dry-run';
const RUN_MODES: readonly AgentRunMode[] = ['apply', 'ask-user', 'dry-run'];

export interface AgentRunRequest {
	id: string;
	kind: AgentRequestKind;
	/** The listening session it was written for (from listener.json); others are rejected. */
	session: string;
	/** Folder-relative `.py` file to run instead of plugin.py; null runs the plugin. */
	script: string | null;
	params: Record<string, unknown> | null;
	mode: AgentRunMode;
}

/**
 * `interrupted`: the editor stopped (closed, crashed, disconnected) mid-run; whether the design
 * changed is unknown. `cancelled`: stopped, declined, or dev mode turned off; nothing applied.
 */
export type AgentRunStatus =
	'running' | 'done' | 'error' | 'rejected' | 'cancelled' | 'interrupted';

/**
 * What happened to the run's result. `nothing`: the run produced no change to apply. `dry-run`:
 * the change was previewed on a scratch copy and thrown away.
 */
export type AgentApplyOutcome =
	'applied' | 'nothing' | 'pending-review' | 'dry-run' | 'stale' | 'not-owner' | 'failed';

/** `runs/<id>.json`: what an agent needs to judge a run, and the context it ran in. */
export interface AgentRunRecord {
	protocol: number;
	id: string;
	kind: AgentRequestKind;
	status: AgentRunStatus;
	pluginId: string;
	session: string | null;
	docId: string | null;
	docName: string | null;
	script: string | null;
	/** SHA-256 of the exact zip that ran: manifest, helper modules and the script together. */
	bundleSha256: string | null;
	scriptSha256: string | null;
	manifestVersion: string | null;
	runtime: string | null;
	activeRegionId: string | null;
	params: Record<string, unknown>;
	/** Null for `describe` and for requests rejected unread. */
	mode: AgentRunMode | null;
	/** `mode === 'apply'`; kept for older run.py copies. */
	apply: boolean;
	startedAt: string;
	finishedAt: string | null;
	durationMs: number | null;
	applyOutcome: AgentApplyOutcome | null;
	/** True only when this run's own result was applied. */
	applied: boolean;
	/** Set once a result left for review is applied, discarded, replaced or found stale. */
	review: 'applied' | 'discarded' | 'superseded' | 'stale' | 'failed' | null;
	summary: string | null;
	mutationCount: number | null;
	/** SHA-256 of the part JSON before and after; others' edits change it too. */
	designBefore: string | null;
	designAfter: string | null;
	logs: string[];
	result: Record<string, unknown> | null;
	artifacts: string[];
	error: string | null;
	traceback: string | null;
	/**
	 * The design's structure after the run, or for a dry run the scratch copy's (no sequences); see
	 * `buildDesignOverview`.
	 */
	overview: DesignOverview | null;
}

export type AgentListenerState = 'listening' | 'paused' | 'stopped';

/** What the listening editor is busy with; run.py prints it while it waits. */
export type AgentListenerActivity = 'idle' | 'running' | 'awaiting-review' | 'awaiting-user';

/** `listener.json`: lets run.py tell "no editor is listening" from "the run is slow". */
export interface AgentListenerInfo {
	protocol: number;
	pluginId: string;
	folderName: string;
	/** The one design runs apply to. */
	docId: string;
	docName: string;
	/** New each time listening starts; a request must carry it. */
	session: string | null;
	state: AgentListenerState;
	/** Why the listener is paused, for run.py to print. */
	reason: string | null;
	activity: AgentListenerActivity;
	/** The request being run, while `activity` is `running`. */
	requestId: string | null;
	heartbeatAt: number;
}

export class AgentRequestError extends Error {
	constructor(
		message: string,
		/** The id the rejection is filed under. */
		readonly id: string
	) {
		super(message);
		this.name = 'AgentRequestError';
	}
}

const ID_PATTERN = /^[A-Za-z0-9_-]{1,80}$/;

/** A request file name (`<id>.json`) → its id; null for temp files and anything else. */
export function requestIdFromFileName(name: string): string | null {
	if (!name.endsWith('.json')) return null;
	const id = name.slice(0, -'.json'.length);
	return ID_PATTERN.test(id) ? id : null;
}

/** Relative, inside the folder, a `.py` file, and not under a dot-folder. */
export function isSafeScriptPath(path: string): boolean {
	if (!path.endsWith('.py') || path.startsWith('/') || path.includes('\\')) return false;
	return path.split('/').every((part) => part !== '' && part !== '..' && !part.startsWith('.'));
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
	return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function requestMode(raw: Record<string, unknown>): unknown {
	if (raw.mode !== undefined) return raw.mode;
	// A run.py from before `mode` sends `apply`; false meant "leave it for the user".
	if (raw.apply === undefined || raw.apply === true) return 'apply';
	return raw.apply === false ? 'ask-user' : null;
}

export function parseAgentRunRequest(text: string, fileId: string): AgentRunRequest {
	let raw: unknown;
	try {
		raw = JSON.parse(text);
	} catch (e) {
		throw new AgentRequestError(
			`The request is not valid JSON: ${e instanceof Error ? e.message : String(e)}`,
			fileId
		);
	}
	if (!isPlainObject(raw))
		throw new AgentRequestError('The request must be a JSON object.', fileId);
	if (raw.protocol !== AGENT_PROTOCOL) {
		throw new AgentRequestError(
			`Protocol ${String(raw.protocol)} is not supported; this editor speaks protocol ${AGENT_PROTOCOL}. ` +
				'Turn agent runs off and on again in Plugin dev mode to update .foldnano/run.py.',
			fileId
		);
	}
	if (raw.id !== fileId) {
		throw new AgentRequestError(`The request id must match its file name ("${fileId}").`, fileId);
	}
	if (typeof raw.session !== 'string' || raw.session === '') {
		throw new AgentRequestError('"session" must be the session from listener.json.', fileId);
	}
	const kind = raw.kind ?? 'run';
	if (kind !== 'run' && kind !== 'describe') {
		throw new AgentRequestError('"kind" must be "run" or "describe".', fileId);
	}
	const script = raw.script ?? null;
	if (kind === 'describe' && script !== null) {
		throw new AgentRequestError('A "describe" request runs no script.', fileId);
	}
	if (script !== null && (typeof script !== 'string' || !isSafeScriptPath(script))) {
		throw new AgentRequestError(
			'"script" must be a relative path to a .py file inside the folder (no "..", no dot-folders).',
			fileId
		);
	}
	const params = raw.params ?? null;
	if (params !== null && !isPlainObject(params)) {
		throw new AgentRequestError('"params" must be a JSON object.', fileId);
	}
	const mode = requestMode(raw);
	if (!RUN_MODES.includes(mode as AgentRunMode)) {
		throw new AgentRequestError('"mode" must be "apply", "ask-user" or "dry-run".', fileId);
	}
	return { id: fileId, kind, session: raw.session, script, params, mode: mode as AgentRunMode };
}

/** The same zip with `path` set to `bytes`: how a script run swaps in its entrypoint. */
export function zipWithFile(zip: Uint8Array, path: string, bytes: Uint8Array): Uint8Array {
	return zipSync({ ...unzipSync(zip), [path]: bytes });
}

export function isoTime(ms: number): string {
	return new Date(ms).toISOString();
}

export async function sha256Hex(data: Uint8Array | string): Promise<string> {
	const bytes = typeof data === 'string' ? new TextEncoder().encode(data) : data;
	const digest = await crypto.subtle.digest('SHA-256', bytes as BufferSource);
	return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, '0')).join('');
}

/** A run.py Foldnano wrote (any protocol), which it may replace. */
export function isGeneratedAgentCli(text: string): boolean {
	return text.includes(CLI_MARKER);
}

export function agentCliText(): string {
	return AGENT_CLI_SOURCE;
}

/** Where an agent learns the API this plugin's format uses; the stubs are always local. */
function formatApiText(manifest: PluginManifest): string {
	// plugin.pyi only re-exports PluginContext; the class is in the package's __init__.pyi.
	const ctx = `\`${STUBS_DIR}/foldnano/__init__.pyi\` (\`PluginContext\`: what \`ctx\` offers)`;
	const preview =
		manifest.applyStrategy === 'previewOnly'
			? '\n- This plugin is `previewOnly`: runs never change the design. Report with `print()` or\n  `ctx.set_result({...})`.'
			: '';
	if (manifest.format === 'foldnano_mini') {
		return `The stubs have the exact signatures and work offline:

- ${ctx}
- \`${STUBS_DIR}/foldnano_mini/\`: the design as mutable Python objects. Start with
  \`__init__.pyi\` (\`load_part\`), then \`part.pyi\`, \`oligo.pyi\`, \`vh.pyi\`, \`region.pyi\`.

Pattern: \`part = load_part(ctx.get_part_as_foldnano_json(), active_region_id=ctx.active_region_id)\`,
change \`part\`, then \`ctx.set_result_mutation_log(part.mutation_log)\`. Each change is recorded as
an operation the editor replays; only use the API, never edit the JSON.${preview}`;
	}
	const io =
		manifest.format === 'cadnano_json'
			? '`ctx.get_part_as_cadnano_json()` gives the active lattice region as cadnano JSON;\n`ctx.set_result_cadnano_json(...)` replaces that region.'
			: '`ctx.get_part_as_foldnano_json()` gives the whole part as JSON;\n`ctx.set_result_foldnano_json(...)` replaces the part.';
	return `The stubs have the exact signatures and work offline:

- ${ctx}
- \`${STUBS_DIR}/foldnano/\`: read-only helpers for parsing the design.

${io} Each applied run replaces it whole, so a mistake anywhere in the JSON
shows up in the result. For step-by-step design edits, ask the user for a \`foldnano_mini\` plugin
(apply strategy \`replayMutationLog\`): it records each change as an operation.${preview}`;
}

/** `python .foldnano/run.py <args>  # comment` lines with the comments lined up. */
function commandLines(commands: [args: string, comment: string][]): string {
	const lines = commands.map(([args, comment]) => [
		`python .foldnano/run.py ${args}`.trimEnd(),
		comment,
	]);
	const width = Math.max(...lines.map(([command]) => command.length)) + 2;
	return lines.map(([command, comment]) => `${command.padEnd(width)}# ${comment}`).join('\n');
}

/** Doc-site pages (plugin-development slugs) for the format, most specific first. */
function apiPages(manifest: PluginManifest): string[] {
	const formatPage = manifest.format === 'foldnano_mini' ? 'foldnano-mini-api' : 'plugin-api';
	return [formatPage, 'context-api', 'plugin-formats', 'plugin-patterns'];
}

