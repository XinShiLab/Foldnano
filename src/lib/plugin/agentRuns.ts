const AGENTS_MD_MARKER =
	/\n<!-- Generated by Foldnano \(agent runs\)[^\n]*sha256:([0-9a-f]{64}) -->\n$/;

/**
 * AGENTS.md as Foldnano writes it: the text, then a marker with the text's hash, so a later
 * version can replace it as long as nobody edited it (\`isUneditedAgentsMd\`).
 */
export async function agentsMdFile(manifest: PluginManifest, origin: string): Promise<string> {
	const body = agentsMdText(manifest, origin);
	return (
		`${body}\n<!-- Generated by Foldnano (agent runs); updated while unedited, yours once you ` +
		`edit it. sha256:${await sha256Hex(body)} -->\n`
	);
}

/** An AGENTS.md Foldnano wrote that nobody has edited since: its text still matches the hash. */
export async function isUneditedAgentsMd(text: string): Promise<boolean> {
	const match = AGENTS_MD_MARKER.exec(text);
	return match !== null && (await sha256Hex(text.slice(0, match.index))) === match[1];
}

