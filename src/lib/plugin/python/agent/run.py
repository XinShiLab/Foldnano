#!/usr/bin/env python3
"""Run Python in the open Foldnano editor from the command line.

Generated by Foldnano (agent runs). Foldnano replaces this file when the protocol changes; keep
your own tools elsewhere. Standard library only, Python 3.9+.

    python .foldnano/run.py                                 # run the plugin (plugin.py)
    python .foldnano/run.py agent-scripts/02-step.py        # run a script and apply its change
    python .foldnano/run.py agent-scripts/02-step.py --dry-run
        # run it and show what it would change; the design is not touched
    python .foldnano/run.py agent-scripts/02-step.py --ask-user-approval
        # run it for real, then wait for the user to Apply or Discard the change
    python .foldnano/run.py --describe                      # the design's structure; runs nothing

After each run it prints an overview of the design's structure (helices, scaffold route, staple
lengths; never sequences): after a dry run, the design as it would be. --no-overview leaves it out.

Exit codes: 0 the run succeeded (and its change was applied, by Foldnano or by the user; for a dry
run, it would apply), 1 it failed, was rejected or cancelled, or its change was not applied,
2 no Foldnano tab is listening or the wait timed out, 3 usage or protocol error.
"""

from __future__ import annotations

import argparse
import json
import os
import secrets
import sys
import textwrap
import time
from pathlib import Path

PROTOCOL = 1
# The editor writes its heartbeat every few seconds, also during a run; older than this means no
# tab is listening.
STALE_AFTER_S = 15.0
POLL_S = 0.2

EXIT_OK, EXIT_FAILED, EXIT_NOT_LISTENING, EXIT_USAGE = 0, 1, 2, 3

FINAL_STATUSES = ("done", "error", "rejected", "cancelled", "interrupted")
NO_APPLY_RENAMED = (
    "--no-apply is gone. Use --dry-run to see what a script would change without changing the "
    "design, or --ask-user-approval to make the change for real once the user clicks Apply."
)
WAITING_MESSAGES = {
    "running": "Waiting for the editor to finish another run.",
    "awaiting-review": "Waiting for the user to Apply or Discard an earlier result in Foldnano.",
    "awaiting-user": "Waiting for the user to answer a prompt in Foldnano.",
}


def folder_root() -> Path:
    """The linked plugin folder: this file lives in its .foldnano/ folder."""
    return Path(__file__).resolve().parent.parent


def agent_dir(root: Path) -> Path:
    return root / ".foldnano" / "agent"


def read_json(path: Path):
    """The parsed file, or None while it is missing or being replaced."""
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def read_listener(root: Path):
    info = read_json(agent_dir(root) / "listener.json")
    return info if isinstance(info, dict) else None


def listener_problem(info, now: float | None = None) -> tuple[str, int] | None:
    """Why no run can start now (message, exit code), or None when an editor is listening."""
    hint = "Open the design in Foldnano and turn on Plugins → Dev → Agent runs for this folder."
    if info is None:
        return f"No Foldnano tab has listened in this folder yet. {hint}", EXIT_NOT_LISTENING
    if info.get("protocol") != PROTOCOL:
        return (
            f"The editor speaks protocol {info.get('protocol')}, this run.py speaks {PROTOCOL}. "
            "Turn agent runs off and on again in Foldnano to update .foldnano/run.py.",
            EXIT_USAGE,
        )
    age = (now if now is not None else time.time()) - float(info.get("heartbeatAt", 0)) / 1000
    if info.get("state") == "stopped" or age > STALE_AFTER_S:
        return f"No Foldnano tab is listening in this folder. {hint}", EXIT_NOT_LISTENING
    if info.get("state") == "paused" or not info.get("session"):
        reason = info.get("reason") or "the editor paused agent runs"
        return f"Foldnano is not accepting runs right now: {reason}", EXIT_NOT_LISTENING
    return None


def new_request_id() -> str:
    """Sorts by time, so the editor runs requests in the order they were made."""
    return f"{int(time.time() * 1000)}-{secrets.token_hex(3)}"


def write_request(root: Path, request: dict) -> Path:
    """Writes atomically (temp file + rename) so the editor never reads half a request."""
    requests = agent_dir(root) / "requests"
    requests.mkdir(parents=True, exist_ok=True)
    final = requests / f"{request['id']}.json"
    temp = requests / f".{request['id']}.tmp"
    temp.write_text(json.dumps(request, indent=2), encoding="utf-8")
    os.replace(temp, final)
    return final


def withdraw(request_path: Path) -> None:
    """Takes back a request nobody picked up, so it can't run later by surprise."""
    try:
        request_path.unlink()
    except FileNotFoundError:
        pass


def awaiting_user(record: dict) -> bool:
    """A real change held for the user's Apply or Discard, not decided yet."""
    return (
        record.get("mode") == "ask-user"
        and record.get("applyOutcome") == "pending-review"
        and not record.get("review")
    )


def wait_for_record(
    root: Path, request_id: str, session: str, timeout_s: float
) -> tuple[dict | None, int | None]:
    """Polls runs/<id>.json until the run ends. Returns (record, None) or (None, exit code).

    Waits as long as the editor's heartbeat is fresh: a long run, or a result waiting for the
    user's review, is not a reason to give up. With --ask-user-approval it also waits for the
    user to Apply or Discard the change.
    """
    record_path = agent_dir(root) / "runs" / f"{request_id}.json"
    request_path = agent_dir(root) / "requests" / f"{request_id}.json"
    started = time.time()
    told = None
    while True:
        record = read_json(record_path)
        acked = isinstance(record, dict)
        if acked and record.get("status") in FINAL_STATUSES and not awaiting_user(record):
            return record, None
        info = read_listener(root)
        problem = listener_problem(info)
        if problem or (not acked and info.get("session") != session):
            if not acked:
                withdraw(request_path)
                message = problem[0] if problem else "The editor started a new session; run again."
            elif awaiting_user(record):
                message = (
                    "The editor stopped before the user applied or discarded the change; it was "
                    "most likely not applied. Check the design (--describe) before running again."
                )
            else:
                message = (
                    "The editor stopped while the script ran; check the design in Foldnano "
                    f"(see {record_path.relative_to(root)})."
                )
            print(message, file=sys.stderr)
            return None, EXIT_NOT_LISTENING
        activity = info.get("activity")
        if not acked and activity in WAITING_MESSAGES and activity != told:
            print(f"[foldnano] {WAITING_MESSAGES[activity]}", file=sys.stderr)
            told = activity
        if acked and awaiting_user(record) and told != "approval":
            print(
                "[foldnano] Waiting for the user to Apply or Discard this change in Foldnano.",
                file=sys.stderr,
            )
            told = "approval"
        if time.time() - started > timeout_s:
            if acked and awaiting_user(record):
                print(
                    f"Gave up waiting after {timeout_s:.0f} s; the change still waits for the user "
                    "in Foldnano. Don't run the script again: if the user clicks Apply, the change "
                    "is made. Check later with --describe.",
                    file=sys.stderr,
                )
                return None, EXIT_NOT_LISTENING
            if not acked:
                withdraw(request_path)
            print(
                f"Gave up after {timeout_s:.0f} s"
                + ("; the run may still finish in the editor" if acked else "")
                + f" (see {record_path.relative_to(root)}).",
                file=sys.stderr,
            )
            return None, EXIT_NOT_LISTENING
        time.sleep(POLL_S)


def parse_param(text: str) -> tuple[str, object]:
    """key=value; the value is JSON when it parses (3, true, [1,2]), else a string."""
    key, sep, value = text.partition("=")
    if not sep or not key:
        raise argparse.ArgumentTypeError(f"expected key=value, got {text!r}")
    try:
        return key, json.loads(value)
    except json.JSONDecodeError:
        return key, value


def script_path(root: Path, given: str) -> str:
    """The script as a folder-relative POSIX path; it must exist inside the folder."""
    path = Path(given)
    full = (path if path.is_absolute() else Path.cwd() / path).resolve()
    try:
        relative = full.relative_to(root)
    except ValueError:
        raise SystemExit(f"{given} is not inside the linked folder {root}") from None
    if not full.is_file():
        raise SystemExit(f"{given} does not exist")
    if full.suffix != ".py":
        raise SystemExit(f"{given} is not a .py file")
    return relative.as_posix()


def succeeded(record: dict) -> bool:
    """Done, and its change applied (by Foldnano or the user), or for a dry run, it would apply."""
    if record.get("status") != "done":
        return False
    outcome = record.get("applyOutcome")
    if outcome == "nothing" or record.get("kind") == "describe":
        return True
    mode = record.get("mode")
    if mode == "dry-run":
        return outcome == "dry-run"
    if mode == "ask-user":
        return record.get("review") == "applied"
    return outcome == "applied"


def wrapped(label: str, items: list[str], more: int = 0, indent: str = "    ") -> list[str]:
    """`label: a  b  c` wrapped at 100 columns, with "… N more" when the list was cut."""
    if more > 0:
        items = [*items, f"… {more} more"]
    return textwrap.wrap(
        f"{label}: {'  '.join(items)}",
        width=100,
        initial_indent=indent,
        subsequent_indent=indent + "  ",
        break_on_hyphens=False,
    )


def count(n: int, noun: str, plural: str | None = None) -> str:
    return f"{n} {noun if n == 1 else plural or noun + 's'}"


def place(item: dict) -> str:
    return f"{item['helix']}[{item['from']}→{item['to']}]"


def format_overview(overview: dict, heading: str = "design now") -> list[str]:
    """The overview the editor put in the record, as lines for the terminal."""
    region = overview["region"]
    bp = region["bpRange"]
    lines = [
        f"[foldnano] {heading}: region \"{region['name']}\" ({region['kind'].lower()}), "
        f"{count(region['helixCount'], 'helix', 'helices')}, bp {bp['min']}–{bp['max']}"
    ]
    helices = [
        f"{h['number']}" + (f"({h['cell']['row']},{h['cell']['col']})" if h.get("cell") else "")
        for h in region["helices"]
    ]
    if helices:
        lines += wrapped(
            "helices, number(row,col)", helices, region["helixCount"] - len(helices), indent="  "
        )
    if not overview["scaffolds"]:
        lines.append("  scaffold: none")
    for i, scaffold in enumerate(overview["scaffolds"], start=1):
        name = "scaffold" if overview["scaffoldCount"] == 1 else f"scaffold {i}"
        lines.append(
            f"  {name}: {scaffold['lengthNt']} nt, "
            f"{'circular' if scaffold['circular'] else 'linear'}, "
            f"{count(scaffold['segmentCount'], 'segment')}, "
            f"{count(scaffold['crossoverCount'], 'crossover')}"
        )
        lines += wrapped("helix order", [" → ".join(str(h) for h in scaffold["helixOrder"])])
        lines += wrapped(
            "route 5'→3'",
            [place(s) for s in scaffold["route"]],
            scaffold["segmentCount"] - len(scaffold["route"]),
        )
        if scaffold["unpairedNt"]:
            lines += wrapped(
                f"unpaired {scaffold['unpairedNt']} nt",
                [place(s) for s in scaffold["unpaired"]],
            )
    if overview["scaffoldCount"] > len(overview["scaffolds"]):
        lines.append(f"  … {overview['scaffoldCount'] - len(overview['scaffolds'])} more scaffolds")
    staples = overview["staples"]
    span = staples.get("lengthNt")
    allowed = f"{staples['range']['min']}–{staples['range']['max']} nt"
    if span:
        lines.append(
            f"  staples: {staples['count']}, {span['min']}–{span['max']} nt "
            f"(median {span['median']:g}), {staples['outsideRangeCount']} outside {allowed}"
            + (f", {staples['circular']} circular" if staples["circular"] else "")
        )
        lines += wrapped(
            "lengths", [f"{b['from']}–{b['to']}:{b['count']}" for b in staples["histogram"]]
        )
        if staples["outsideRange"]:
            lines += wrapped(
                f"outside {allowed}, by 5' end",
                [f"{s['helix']}[{s['bp']}] {s['lengthNt']} nt" for s in staples["outsideRange"]],
                staples["outsideRangeCount"] - len(staples["outsideRange"]),
            )
    else:
        lines.append("  staples: none")
    for other in overview.get("otherRegions") or []:
        lines.append(
            f"  other region: \"{other['name']}\" ({other['kind'].lower()}, "
            f"{count(other['helixCount'], 'helix', 'helices')})"
        )
    return lines


def print_overview(record: dict) -> None:
    overview = record.get("overview")
    if not overview:
        return
    dry_run = record.get("applyOutcome") == "dry-run"
    heading = "design if applied (dry run; nothing changed)" if dry_run else "design now"
    for line in format_overview(overview, heading):
        print(line)
    if record.get("applyOutcome") == "pending-review" and not record.get("review"):
        print("  (the change waiting for the user is not in it yet)")


def print_record(record: dict, overview: bool = True) -> None:
    if record.get("kind") == "describe" and record.get("status") == "done":
        print_overview(record)
        return
    for line in record.get("logs") or []:
        print(line)
    status = record.get("status")
    if status == "done":
        outcome = record.get("applyOutcome")
        review = record.get("review")
        if outcome == "pending-review" and review:
            label = {
                "applied": "done · applied by the user (one undo step)",
                "discarded": "done · NOT applied: the user discarded it",
                "superseded": "done · NOT applied: a newer result replaced it",
                "stale": "done · NOT applied: the design changed before the user applied it",
                "failed": "done · NOT applied: applying it failed",
            }.get(review, f"done · {review}")
        else:
            label = {
                "applied": "done · applied (one undo step)",
                "nothing": "done · nothing to apply",
                "pending-review": "done · waiting for the user to Apply or Discard",
                "dry-run": "done · dry run: the design was not changed",
                "stale": "done · NOT applied: the design changed while the script ran",
                "not-owner": "done · NOT applied: another tab owns the design",
            }.get(outcome, "done")
        bits = [label]
        if record.get("summary"):
            bits.append(record["summary"])
        if record.get("durationMs") is not None:
            bits.append(f"{record['durationMs'] / 1000:.1f} s")
        print(f"[foldnano] {' · '.join(bits)}")
        if record.get("result"):
            print(f"[foldnano] result: {json.dumps(record['result'])}")
        if overview:
            print_overview(record)
        if not succeeded(record) and record.get("error"):
            print(f"[foldnano] {record['error']}", file=sys.stderr)
        return
    print(f"[foldnano] {status}: {record.get('error') or 'no message'}", file=sys.stderr)
    if record.get("traceback"):
        print(record["traceback"], file=sys.stderr)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python .foldnano/run.py",
        description="Run the plugin, or a script in this folder, in the open Foldnano editor.",
    )
    parser.add_argument("script", nargs="?", help="a .py file with def run(ctx); default: plugin.py")
    parser.add_argument(
        "--param", action="append", type=parse_param, default=[], metavar="KEY=VALUE"
    )
    review = parser.add_mutually_exclusive_group()
    review.add_argument(
        "--dry-run",
        action="store_true",
        help="run, and show what the change would be (overview included); the design is not touched",
    )
    review.add_argument(
        "--ask-user-approval",
        action="store_true",
        help="run, then wait for the user to Apply or Discard the change: a real edit if applied",
    )
    parser.add_argument("--no-apply", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument(
        "--describe",
        action="store_true",
        help="print an overview of the design's structure; runs no Python",
    )
    parser.add_argument(
        "--no-overview", action="store_true", help="don't print the overview after the run"
    )
    parser.add_argument("--timeout", type=float, default=600, help="seconds to wait (default 600)")
    parser.add_argument("--json", action="store_true", help="print the run record as JSON")
    args = parser.parse_args(argv)
    if args.no_apply:
        print(NO_APPLY_RENAMED, file=sys.stderr)
        return EXIT_USAGE
    if args.describe and (args.script or args.param or args.dry_run or args.ask_user_approval):
        print(
            "--describe runs nothing; it takes no script, --param, --dry-run or --ask-user-approval",
            file=sys.stderr,
        )
        return EXIT_USAGE

    root = folder_root()
    info = read_listener(root)
    problem = listener_problem(info)
    if problem:
        print(problem[0], file=sys.stderr)
        return problem[1]

    request = {
        "protocol": PROTOCOL,
        "id": new_request_id(),
        "kind": "describe" if args.describe else "run",
        "session": info["session"],
        "script": script_path(root, args.script) if args.script else None,
        "params": dict(args.param) or None,
        "mode": "dry-run" if args.dry_run else "ask-user" if args.ask_user_approval else "apply",
    }
    verb = "describing" if args.describe else "running on"
    print(f"[foldnano] {verb} the design \"{info.get('docName', '')}\"", file=sys.stderr)
    write_request(root, request)
    record, code = wait_for_record(root, request["id"], request["session"], args.timeout)
    if record is None:
        return code if code is not None else EXIT_NOT_LISTENING
    if args.json:
        print(json.dumps(record, indent=2))
    else:
        print_record(record, overview=not args.no_overview)
    return EXIT_OK if succeeded(record) else EXIT_FAILED


if __name__ == "__main__":
    sys.exit(main())
