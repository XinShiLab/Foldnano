/** Published (non-draft) entries, newest first. */
export function publishedWhatsNew(entries: readonly WhatsNewEntry[] = WHATS_NEW): WhatsNewEntry[] {
	return entries.filter((entry) => !entry.draft).sort((a, b) => b.date.localeCompare(a.date));
}

export const RECENT_WINDOW_MONTHS = 3;

/**
 * Split newest-first entries into those within `months` of the newest entry and the rest.
 * Anchored on the newest entry, not today, so a quiet period never empties the recent list.
 */
export function splitByRecency(
	entries: readonly WhatsNewEntry[],
	months: number = RECENT_WINDOW_MONTHS
): { recent: WhatsNewEntry[]; earlier: WhatsNewEntry[] } {
	if (entries.length === 0) return { recent: [], earlier: [] };
	const cutoff = new Date(`${entries[0].date}T00:00:00Z`);
	cutoff.setUTCMonth(cutoff.getUTCMonth() - months);
	const cutoffDate = cutoff.toISOString().slice(0, 10);
	return {
		recent: entries.filter((entry) => entry.date >= cutoffDate),
		earlier: entries.filter((entry) => entry.date < cutoffDate),
	};
}

export const ANNOUNCEMENT_DEFAULT_DAYS = 90;

export interface PendingAnnouncement {
	readonly announcement: WhatsNewAnnouncement;
	/** The entry's `link`; without it, "Read more" opens What's New. */
	readonly link?: GuideLink;
	/** Older unseen announcements still in their window, folded into "and N earlier updates". */
	readonly earlierCount: number;
}

/** Last day an announcement is shown. */
export function announcementShowUntil(entry: WhatsNewEntry): string | null {
	if (!entry.announce) return null;
	if (entry.announce.showUntil) return entry.announce.showUntil;
	const until = new Date(`${entry.date}T00:00:00Z`);
	until.setUTCDate(until.getUTCDate() + ANNOUNCEMENT_DEFAULT_DAYS);
	return until.toISOString().slice(0, 10);
}

/** Published announcements, newest id first, including expired ones. */
export function publishedAnnouncements(
	entries: readonly WhatsNewEntry[] = WHATS_NEW
): { entry: WhatsNewEntry; announcement: WhatsNewAnnouncement }[] {
	return publishedWhatsNew(entries)
		.flatMap((entry) => (entry.announce ? [{ entry, announcement: entry.announce }] : []))
		.sort((a, b) => b.announcement.id.localeCompare(a.announcement.id));
}

/** Newest published announcement id, expired or not; what a first visit marks as seen. */
export function latestAnnouncementId(entries: readonly WhatsNewEntry[] = WHATS_NEW): string | null {
	return publishedAnnouncements(entries)[0]?.announcement.id ?? null;
}

/** The announcement to show given the seen watermark, or null. `today` is YYYY-MM-DD. */
export function pendingAnnouncement(
	seenId: string | null,
	today: string,
	entries: readonly WhatsNewEntry[] = WHATS_NEW
): PendingAnnouncement | null {
	const unseen = publishedAnnouncements(entries).filter(
		({ entry, announcement }) =>
			(seenId === null || announcement.id > seenId) && (announcementShowUntil(entry) ?? '') >= today
	);
	if (unseen.length === 0) return null;
	const { entry, announcement } = unseen[0];
	return { announcement, link: entry.link, earlierCount: unseen.length - 1 };
}

/**
 * New watermark after the user dismissed `requestedId`, or null when the request is not a
 * published announcement. Never moves back, so an old tab can't resurface a newer announcement.
 */
export function advanceAnnouncementWatermark(
	currentId: string | null,
	requestedId: string,
	entries: readonly WhatsNewEntry[] = WHATS_NEW
): string | null {
	const known = publishedAnnouncements(entries).some(
		({ announcement }) => announcement.id === requestedId
	);
	if (!known) return null;
	return currentId !== null && currentId > requestedId ? currentId : requestedId;
}

/**
 * Identifies the newest published entry for the unread dot: its date plus how many entries share
 * it, so a second entry on the same day still counts as new.
 */
export function latestEntryKey(entries: readonly WhatsNewEntry[] = WHATS_NEW): string | null {
	const published = publishedWhatsNew(entries);
	const newest = published[0]?.date;
	if (!newest) return null;
	return `${newest}#${published.filter((entry) => entry.date === newest).length}`;
}

/**
 * How many of the newest published entries are unread for `seenKey` (a `latestEntryKey()` value).
 * Unread entries are always the first ones in `publishedWhatsNew()` order, since new entries go on
 * top. No key (first visit, or from before the cookie existed) counts as none unread.
 */
export function unreadEntryCount(
	seenKey: string | null,
	entries: readonly WhatsNewEntry[] = WHATS_NEW
): number {
	const match = seenKey?.match(/^(\d{4}-\d{2}-\d{2})#(\d+)$/);
	if (!match) return 0;
	const [, seenDate, seenCount] = match;
	const published = publishedWhatsNew(entries);
	const newer = published.filter((entry) => entry.date > seenDate).length;
	const sameDay = published.filter((entry) => entry.date === seenDate).length;
	return newer + Math.max(0, sameDay - Number(seenCount));
}
