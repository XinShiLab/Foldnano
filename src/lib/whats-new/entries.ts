import type { GuideLink } from '$lib/components/help/help';

/** A one-time card shown in the editor for a major change; see `docs/whats-new.md`. */
export interface WhatsNewAnnouncement {
	/** Starts with the entry's date (YYYY-MM-DD-…); ids sort in release order and are never reused. */
	readonly id: string;
	readonly title: string;
	/** One or two sentences; say whether existing designs are affected. */
	readonly body: string;
	/** Last day (YYYY-MM-DD) it is shown; defaults to `ANNOUNCEMENT_DEFAULT_DAYS` after `date`. */
	readonly showUntil?: string;
}

export interface WhatsNewEntry {
	/** ISO date (YYYY-MM-DD) the change landed. */
	readonly date: string;
	/** Short feature area, e.g. "Strand view" or "Plugins". */
	readonly area: string;
	/** User-facing description; one or two sentences. */
	readonly text: string;
	/** Generated by `pnpm whats-new:draft`; hidden in the app until the flag is removed. */
	readonly draft?: boolean;
	/** Guide page for more detail: "Learn more" in What's New and "Read more" on its announcement. */
	readonly link?: GuideLink;
	/** Major change: also shown once as an announcement to returning users. Use rarely. */
	readonly announce?: WhatsNewAnnouncement;
}

